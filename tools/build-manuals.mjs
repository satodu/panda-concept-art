#!/usr/bin/env node
// Generates <concept>/MANUAL.md: ONE self-contained file to send to any AI together with
// "what I want" + "my primary color". Same format as the original prompt manual.
//   node tools/build-manuals.mjs
import {writeFileSync, readFileSync} from 'node:fs';
import {join, dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {styles} from './prompt-data.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SLUGS = {'oriental-brutalismo': 'oriental-brutalismo', galdr: 'galdr', shizuka: 'shizuka'};
const WORDS = {'oriental-brutalismo': ['magenta'], galdr: [], shizuka: ['faded red (shu)', 'faded red']};
const PC = '[PRIMARY COLOR]';

const build = (key, s) => {
  const slug = SLUGS[key];
  const tok = JSON.parse(readFileSync(join(root, slug, 'tokens', 'tokens.json'), 'utf8'));
  const sw = (t) => {
    t = t.replaceAll(`${s.primary.name} (${s.primary.hex})`, PC).replaceAll(s.primary.hex, PC);
    for (const w of WORDS[key]) t = t.replaceAll(w, 'primary-color');
    return t;
  };
  const BASE = sw(`${s.palette}. ${s.base}.`);
  const NEG = s.negatives;
  const noText = 'no readable text, no letters, no logos';
  const P = `[PRIMARY COLOR]`;
  const prompt = (n, title, use, body) => `### PROMPT ${n} // ${title}\n\n${use}\n\n\`\`\`\n${sw(body)} Avoid: ${NEG}.\n\`\`\`\n`;
  const c = tok.color;
  const rows = Object.entries(c).map(([k, v]) => `| \`${k}\` | \`${v}\` |`).join('\n');
  const ex = s.primary.alt.map((a) => `\`${a}\``).join(', ');

  return `# ${s.title}. PROMPT MANUAL

[ SYSTEM.DOC // MANUAL // REV.03 ] | Generated by \`tools/build-manuals.mjs\`. Do not edit by hand.

**How to use (3 steps):**
1. Send this whole file to the AI (Midjourney, Flux, DALL-E, Gemini, ChatGPT, Claude).
2. Say **what you want** (the subject) and the **primary color** (name + hex).
3. The AI picks the matching prompt below, fills \`[SUBJECT]\` and replaces \`${P}\` with your color.

Default primary: **${s.primary.name} \`${s.primary.hex}\`**. Primary color use is **free**: any color works (examples: ${ex}). Only the primary changes; neutrals, materials, typography and layout stay.

> **Instruction for the AI:** read sections 01 and 02, choose the prompt that fits the request, fill \`[SUBJECT]\` and \`${P}\`, and return only the final prompt. Never print hex codes, style names or this document's labels as text inside the image. Always respect "Avoid".

---

## 01. ART DIRECTION

${BASE}

**Light:** ${s.light}.
**Materials:** ${sw(s.materials)}.
**Typography:** ${s.typo}.
**Ornaments (sparingly):** ${sw(s.ornaments)}.
**Primary color rule:** ${P} on ONE focus per composition; never on large backgrounds.
**Avoid:** ${NEG}.
${s.note ? `**Note:** ${s.note}\n` : ''}
---

## 02. PROMPTS

${prompt('01', 'USER INTERFACE (WEB AND APPS)', 'Screens, dashboards, landing pages, mobile apps.', `High-end UI design concept for [SUBJECT]. ${BASE} ${s.ui.layout}. ${s.ui.components}. Crisp readable real text only, Figma showcase. --ar 16:9`)}
${prompt('02', 'BACKGROUNDS AND WALLPAPERS', 'Wallpapers, section backgrounds, presentation textures.', `Minimal abstract backdrop for [SUBJECT]. ${BASE} Hero element: ${s.hero[0]}. At least 55% empty space, very low contrast, ${noText}. --ar 16:9`)}
${prompt('03', 'ICONS AND BADGES', 'App icon, favicon, project badge, contact or navigation icons.', `Icon for [SUBJECT]: ${s.icon.mark}. Shape: ${s.icon.shape}. ${s.palette}. Centered, flat vector clarity, a lot of empty space, ${noText}. --ar 1:1`)}
${prompt('04', 'PEOPLE (PORTRAIT / ABOUT ME / CHARACTER)', 'Profile photos, "about me" headers, characters.', `${s.people.portrait}, depicting [SUBJECT]. ${BASE} Keep the person's real skin tones and colors natural. --ar 4:5`)}
${prompt('05', 'COMPOSITION FRAME', 'Decorative frame ready to receive an image or mockup.', `Minimal editorial layout frame for [SUBJECT]. ${BASE} Center left open as negative space, details only along the borders. ${noText}. --ar 16:9`)}
${prompt('06', 'BANNER WITH TITLE', 'LinkedIn, X/Twitter, README, launch banners.', `Bold editorial banner with title "[SUBJECT].". ${BASE} Strong typographic hierarchy, ${s.typo}. --ar 3:1`)}
${prompt('07', 'BANNER WITHOUT LETTERS', 'Page headers, blog cards, text added later in code.', `Abstract hero banner for [SUBJECT], free of readable text. Hero element: ${s.hero[1]}. ${BASE} --ar 16:9`)}
${prompt('08', 'DIAGRAM / ARCHITECTURE', 'Technical posts, backend, cloud, data.', `Abstract technical architecture of [SUBJECT] as modular nodes connected by thin lines, the active path in ${P}. ${BASE} Labels short and real. --ar 16:9`)}
${prompt('09', 'TERMINAL / CODE / PRODUCT MOCKUP', 'CLI, source code, app on a device.', `Floating terminal window with syntax-highlighted code about [SUBJECT]. ${BASE} Accent ${P} for keywords only. Real code lines, no gibberish. --ar 16:9`)}
${prompt('10', 'EDIT MY PHOTO (WITH AN INPUT IMAGE)', 'Attach the photo. Keeps the person intact, changes only background and ornaments.', `Edit this image: keep the person exactly as in the original photo (same skin tones, hair, clothes, face, proportions); do not apply any color grade, duotone or tint to the person. Change only the background and add ornaments around the person, at low opacity: ${sw(s.ornaments)}. Background and style: ${BASE} Leave half of the frame as negative space for [SUBJECT].`)}

---

## 03. DESIGN SYSTEM (for code)

You are a front-end specialist. In this project **follow these tokens strictly**; never use generic framework themes.

| Token | Value |
|---|---|
${rows}

- Fonts: display **${tok.font.display}**, body **${tok.font.body}**, mono **${tok.font.mono}**, Japanese **${tok.font.jp}**.
- Layout: ${s.ui.layout}. Components: ${s.ui.components}.
- Voice: ${s.voice.tone}. Samples: ${s.voice.samples.map((x) => `"${x}"`).join(', ')}.
- \`primary\` is the **only** value to swap (CSS: \`--color-primary\`); \`primarySoft\`, \`primaryGlow\` and \`onPrimary\` derive from it. Choose \`onPrimary\` (concept black or white) with the highest contrast.

Full reference: \`${s.master}\`.
`;
};

for (const [key, s] of Object.entries(styles)) {
  writeFileSync(join(root, SLUGS[key], 'MANUAL.md'), build(key, s));
  console.log('+', SLUGS[key], 'MANUAL.md');
}
